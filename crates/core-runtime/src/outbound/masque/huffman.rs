/// Decode a Huffman-coded literal (RFC 7541 5.2).
///
/// Accepts trailing EOS padding (all-ones suffix up to 7 bits); rejects
/// embedded EOS symbols, non-ones padding, and truncated input.
pub(super) fn huffman_decode(input: &[u8]) -> Result<Vec<u8>, ()> {
    let mut out = Vec::with_capacity(input.len() * 2);
    let mut acc: u64 = 0;
    let mut bits: u32 = 0;
    for &byte in input {
        acc = (acc << 8) | u64::from(byte);
        bits += 8;
        while bits >= 5 {
            let mut consumed = false;
            for n in 5..=bits.min(30) {
                let shift = bits - n;
                let v = (acc >> shift) as u32;
                if let Some(sym) = HUFFMAN_CODE
                    .iter()
                    .position(|&(c, l)| u32::from(l) == n && c == v)
                {
                    if sym == 256 {
                        return Err(());
                    }
                    out.push(sym as u8);
                    acc &= (1u64 << shift) - 1;
                    bits = shift;
                    consumed = true;
                    break;
                }
            }
            if !consumed {
                break;
            }
        }
    }
    if bits > 7 {
        return Err(());
    }
    if bits > 0 && acc != (1u64 << bits) - 1 {
        return Err(());
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(s: &str) -> Vec<u8> {
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
            .collect()
    }

    fn encode_raw(s: &[u8]) -> Vec<u8> {
        let mut out = Vec::new();
        let mut acc: u64 = 0;
        let mut bits: u32 = 0;
        for &b in s {
            let (c, n) = HUFFMAN_CODE[b as usize];
            acc = (acc << n) | u64::from(c);
            bits += u32::from(n);
            while bits >= 8 {
                bits -= 8;
                out.push((acc >> bits) as u8);
                acc &= (1u64 << bits) - 1;
            }
        }
        if bits > 0 {
            let pad = 8 - bits;
            acc = (acc << pad) | ((1u64 << pad) - 1);
            out.push(acc as u8);
        }
        out
    }

    #[test]
    fn rfc_7541_examples() {
        assert_eq!(
            huffman_decode(&hex("f1e3c2e5f23a6ba0ab90f4ff")).unwrap(),
            b"www.example.com"
        );
        assert_eq!(huffman_decode(&hex("a8eb10649cbf")).unwrap(), b"no-cache");
        assert_eq!(
            huffman_decode(&hex("25a849e95ba97d7f")).unwrap(),
            b"custom-key"
        );
        assert_eq!(
            huffman_decode(&hex("25a849e95bb8e8b4bf")).unwrap(),
            b"custom-value"
        );
    }

    #[test]
    fn roundtrip_all_byte_values_and_text() {
        let all: Vec<u8> = (0u8..=255).collect();
        let texts: [&[u8]; 6] = [
            b"",
            b"a",
            b"hello world",
            b"Mon, 21 Oct 2013 20:13:21 GMT",
            b"foo=ASDJKHQKBZXOQWEOPIUAXQWEOIU; max-age=3600; version=1",
            &all,
        ];
        for t in texts {
            let coded = encode_raw(t);
            assert_eq!(huffman_decode(&coded).unwrap(), t, "roundtrip {t:?}");
        }
    }

    #[test]
    fn rejects_eos_bad_padding_and_truncation() {
        assert!(huffman_decode(&[0xff, 0xff, 0xff, 0xff]).is_err());
        assert!(huffman_decode(&[0x00]).is_err());
        // valid symbol then a byte of zeros: padding must be all ones
        assert!(huffman_decode(&[0x17, 0x00]).is_err());
    }
}
