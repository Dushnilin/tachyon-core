#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn hpack_table_spot_checks() {
        assert_eq!(HPACK_STATIC.len(), 61);
        assert_eq!(HPACK_STATIC[0], (":authority", ""));
        assert_eq!(HPACK_STATIC[1], (":method", "GET"));
        assert_eq!(HPACK_STATIC[3], (":path", "/"));
        assert_eq!(HPACK_STATIC[60], ("www-authenticate", ""));
        let unique: HashSet<_> = HPACK_STATIC.iter().collect();
        assert_eq!(unique.len(), HPACK_STATIC.len());
    }

    #[test]
    fn qpack_table_spot_checks() {
        assert_eq!(QPACK_STATIC.len(), 99);
        assert_eq!(QPACK_STATIC[0], (":authority", ""));
        assert_eq!(QPACK_STATIC[1], (":path", "/"));
        assert_eq!(QPACK_STATIC[15], (":method", "CONNECT"));
        assert_eq!(QPACK_STATIC[25], (":status", "200"));
        assert_eq!(
            QPACK_STATIC[52],
            ("content-type", "text/html; charset=utf-8")
        );
        assert_eq!(QPACK_STATIC[98], ("x-frame-options", "sameorigin"));
        let unique: HashSet<_> = QPACK_STATIC.iter().collect();
        assert_eq!(unique.len(), QPACK_STATIC.len());
    }
}
